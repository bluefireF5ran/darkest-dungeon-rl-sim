"""A trinket's tier, from the tier lists Fran pointed at (2026-10-01).

Fran, on bosses: *"si me puedo asegurar un muy raro, como siempre dan los
bosses prefiero buscar una que me de una ventaja real"*. Every boss pays a
very rare trinket, so rarity says nothing; the tier says whether this one is
worth the run. In his first recorded session the board offered six boss
rewards and he took none -- and all six sit in the bottom three very-rare
tiers here, which is the check that this list and his play agree.

`data/trinket_tiers.json` is GENERATED by `tools/trinket_tierlist.py` from
the five images in `captures/trinket_tiers/` (one per rarity), by matching
each tile against the game's own icons. Edit the images or the tool, never
the JSON by hand.

A tier is opinion, not game data: it decides what to want, never a number.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Optional

TIERS_FILE = Path(__file__).resolve().parent / "trinket_tiers.json"

#: Ranks counted as "a real advantage", best first: on the very-rare sheet
#: that is `insane` and `pretty good`. Provisional until Fran rules on it.
WORTH_A_BOSS_RANK = 1


@lru_cache(maxsize=1)
def _entries() -> dict:
    try:
        return json.loads(TIERS_FILE.read_text(encoding="utf-8"))["entries"]
    except (OSError, ValueError, KeyError):
        return {}


def tier(trinket_id: str) -> Optional[dict]:
    """The tier-list entry for an id, or None when no list places it."""
    return _entries().get(trinket_id)


def worth_a_boss(trinket_id: str, max_rank: int = WORTH_A_BOSS_RANK) -> bool:
    """True when the trinket is ranked in the top `max_rank + 1` tiers of its
    sheet. A torchless-only pick and an unlisted id are both False: unknown
    is not an advantage."""
    t = tier(trinket_id)
    return bool(t) and t["rank"] is not None and t["rank"] <= max_rank
