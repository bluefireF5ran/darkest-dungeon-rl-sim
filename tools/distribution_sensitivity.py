"""Which training-distribution shift does the policy actually care about?

    python tools/distribution_sensitivity.py --model <ckpt> --knob loadout
    python tools/distribution_sensitivity.py --model <ckpt> --knob kit --self-check

Five knobs landed on 2026-08-20, each defaulting off, each changing what a
training run sees. Turning them all on at once is one retrain and no
attribution — the mistake this project has already made twice. This measures
them **one at a time, against a fixed policy**, before any compute is spent.

The question per knob is the same one `tools/loadout_sensitivity.py` asked for
loadouts and answered at -16.7pp: *the policy trained on one distribution; how
much worse does it play when only this one thing changes?* A large drop says
training against that shift is worth a retrain. A small one says the policy
already generalises there and the retrain would buy noise — which is this
project's oldest failure mode, and the honest outcome is to report it and not
train.

| knob | arm A | arm B |
|---|---|---|
| `loadout` | the comp's curated four | a random legal 4-of-7 |
| `kit` | the comp's trinkets and quirks | a random legal pair + quirk sheet |
| `resolve` | party at the top of its bracket | each hero drawn within it |
| `region` | the comp's tagged Location | a different core region |
| `boss` | an ordinary expedition | the last combat is the region's boss |

**Everything is driven through explicit reset options, not through the env's
own knobs.** The values are generated by a separate seeded env whose knobs are
all on, then handed to a plain env to play. That keeps arm A byte-identical to
production behaviour and means a knob's own sampling can never leak into the
control arm.

**Read `region` and `boss` differently from the other three.** Loadout, kit and
resolve change the *party* while the dungeon stays identical, so the delta is
the policy. Region and boss change the *dungeon itself* — a harder or simply
different fight — so a drop there is partly "this content is harder", not only
"the policy is off-distribution". Both are worth knowing; they are not the same
claim.

`--self-check` plays arm A as both arms. Every delta must be exactly 0.0. Two
measurements in this project have returned a confident, wrong zero, so the
control runs before the result is read rather than after it is doubted.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sb3_contrib import MaskablePPO
from sb3_contrib.common.wrappers import ActionMasker

from env.expedition_env import CORE_ZONE_IDS, UNRESTRICTED_HEROES
from env.expedition_sequence_env import EXPEDITION_LENGTH_BANDS, ExpeditionSequenceEnv
from env.gym_env import mask_fn
from eval_expedition import resolve_skill_ids, run_full_expedition_episode
from tools.ab_compare import (METRICS, RATE_METRICS, bootstrap_ci,
                              build_scenarios, mcnemar_exact)

KNOBS = ("loadout", "kit", "resolve", "region", "boss")


def variant_options(gen, sc, knob: str) -> dict:
    """The `extra_options` that turn arm A's scenario into arm B's.

    `gen` is an env with every knob enabled, used ONLY as a value generator —
    its `_loadout_rng` is reseeded per scenario by the caller, so the same
    `--comp-seed` reproduces the same variation.
    """
    hero_ids = list(sc.hero_ids)
    if knob == "loadout":
        return {"hero_skill_ids": [[] if h in UNRESTRICTED_HEROES
                                   else gen._random_skill_ids(h)
                                   for h in hero_ids]}
    if knob == "kit":
        return {"trinkets_and_quirks": [gen._random_kit(h) for h in hero_ids]}
    if knob == "resolve":
        return {"hero_levels": gen.sample_hero_levels(sc.tier, len(hero_ids))}
    if knob == "boss":
        return {"boss_quest": True}
    if knob == "region":
        others = [z for z in CORE_ZONE_IDS if z != sc.zone_id]
        return {"zone_id": gen._loadout_rng.choice(others)}
    raise ValueError(knob)


def play(env, model, sc, skills, extra):
    """One scenario, reproducibly. The reseed is what pairs the arms: without
    it the enemy draw depends on how many episodes this env has already run,
    so the second arm would face a different dungeon and the delta would be
    luck."""
    env.unwrapped._sampler_rng.seed(sc.ep_seed)
    return run_full_expedition_episode(
        env, model, sc.comp_name, list(sc.hero_ids), sc.zone_id, sc.tier,
        sc.length_band, sc.num_combats, sc.ep_seed,
        hero_skill_ids=skills, extra_options=extra)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True)
    ap.add_argument("--knob", required=True, choices=KNOBS)
    ap.add_argument("--episodes", type=int, default=4,
                    help="episodes per comp x band cell")
    ap.add_argument("--comps", type=int, default=12)
    ap.add_argument("--comp-seed", type=int, default=1,
                    help="1 with --comps 12 reproduces the archived comp set")
    ap.add_argument("--metric", default="success", choices=METRICS)
    ap.add_argument("--bootstrap", type=int, default=10000)
    ap.add_argument("--self-check", action="store_true",
                    help="arm A as BOTH arms; every delta must be 0.0")
    args = ap.parse_args()

    base = ExpeditionSequenceEnv(sampler_seed=None)
    env = ActionMasker(base, mask_fn)
    store = base.store
    # Value generator only — never played. Every knob on so its helpers work.
    gen = ExpeditionSequenceEnv(store=store, sampler_seed=0,
                                loadout_random_p=1.0, kit_random_p=1.0,
                                resolve_sampling=True, cross_region_p=1.0)
    model = MaskablePPO.load(args.model, env=env, device="cpu")

    scenarios = build_scenarios(store, args.comps, args.comp_seed, args.episodes)
    print(f"model: {args.model}")
    print(f"knob:  {args.knob}"
          + ("   (SELF-CHECK: both arms are the control)" if args.self_check else ""))
    print(f"{len(scenarios)} paired scenarios ({args.comps} comps x "
          f"{len(EXPEDITION_LENGTH_BANDS)} bands x {args.episodes} episodes)\n")
    if args.knob in ("region", "boss") and not args.self_check:
        print("  NOTE: this knob changes the DUNGEON, not the party, so a drop\n"
              "  is partly 'this content is harder' and not only 'the policy is\n"
              "  off-distribution'. Read it differently from loadout/kit/resolve.\n")

    rows = []
    for i, sc in enumerate(scenarios, 1):
        curated = resolve_skill_ids(store, sc.comp_name, list(sc.hero_ids))
        gen._loadout_rng.seed(sc.ep_seed)
        extra = {} if args.self_check else variant_options(gen, sc, args.knob)
        rows.append((sc,
                     play(env, model, sc, curated, {}),
                     play(env, model, sc, curated, extra)))
        if i % 20 == 0 or i == len(scenarios):
            print(f"  {i}/{len(scenarios)}")

    print(f"\n  {'metric':<16s} {'control':>9s} {args.knob:>9s} {'delta':>9s}  95% CI")
    for m in METRICS:
        av = [float(getattr(oa, m)) for _s, oa, _o in rows]
        bv = [float(getattr(ob, m)) for _s, _o, ob in rows]
        deltas = [b - a for a, b in zip(av, bv)]
        lo, hi = bootstrap_ci(deltas, iters=args.bootstrap)
        scale = 100.0 if m in RATE_METRICS else 1.0
        unit = "pp" if m in RATE_METRICS else ""
        print(f"  {m:<16s} {statistics.mean(av) * scale:9.2f} "
              f"{statistics.mean(bv) * scale:9.2f} "
              f"{statistics.mean(deltas) * scale:+8.2f}{unit} "
              f" [{lo * scale:+.2f}, {hi * scale:+.2f}]"
              + ("   <-- must be 0.00" if args.self_check else ""))

    m = args.metric
    b = sum(1 for _s, oa, ob in rows if getattr(oa, m) and not getattr(ob, m))
    c = sum(1 for _s, oa, ob in rows if getattr(ob, m) and not getattr(oa, m))
    print(f"\n  {m}: control-only {b}, {args.knob}-only {c}, "
          f"tied {len(rows) - b - c} of {len(rows)}")
    print(f"  exact McNemar p = {mcnemar_exact(b, c):.4f}")
    print("\n  A large drop justifies training against this shift. A small one "
          "says the\n  policy already generalises and the compute would buy "
          "noise -- report it\n  and do not train.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
